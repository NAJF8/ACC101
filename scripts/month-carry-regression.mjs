import assert from 'node:assert/strict';
import { connectAuthEmulator, signInAnonymously, signOut } from 'firebase/auth';
import { connectDatabaseEmulator, get, ref } from 'firebase/database';

const host = process.env.FIREBASE_EMULATOR_HOST || '127.0.0.1';
if (!['127.0.0.1', 'localhost'].includes(host)) throw new Error(`Refusing non-local emulator host: ${host}`);
const projectId = process.env.FIREBASE_PROJECT_ID || 'acc-101';
const { auth, db } = await import('../src/services/firebase.js');
connectAuthEmulator(auth, `http://${host}:9099`, { disableWarnings: true });
connectDatabaseEmulator(db, host, 9000);
const ownerUrl = (path) => `http://${host}:9000/${path}.json?ns=${projectId}-default-rtdb&access_token=owner`;
const ownerSet = async (path, value) => { const r = await fetch(ownerUrl(path), { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify(value) }); if (!r.ok) throw new Error(`seed failed: ${r.status}`); };
const ownerRead = async (path) => (await fetch(ownerUrl(path))).json();
await ownerSet('', null);
const user = (await signInAnonymously(auth)).user;
await ownerSet(`users/${user.uid}`, { id: user.uid, role: 'super_admin', active: true });
await ownerSet('monthly_periods', { '2026-08': { month: '2026-08', status: 'open' }, '2026-09': { month: '2026-09', status: 'open' } });
const { api } = await import('../src/services/api.js');
const first = await api.carryForwardMonth({ sourceMonth: '2026-08', targetMonth: '2026-09', sourceClosingCash: 130000, idempotencyKey: 'month-carry-regression' });
const retry = await api.carryForwardMonth({ sourceMonth: '2026-08', targetMonth: '2026-09', sourceClosingCash: 130000, idempotencyKey: 'month-carry-regression' });
const [record, opening, all] = await Promise.all([get(ref(db, 'cash_carry_forwards/2026-09')), get(ref(db, 'cash_month_openings/2026-09')), ownerRead('cash_carry_forwards')]);
assert.equal(first.carried_amount, 130000);
assert.equal(retry.idempotent, true);
assert.equal(record.val().opening_cash, 130000);
assert.equal(opening.val().opening_cash, 130000);
assert.equal(Object.keys(all || {}).length, 1);
assert.equal(await ownerRead('cash_movements'), null);
assert.equal(await ownerRead('sales'), null);
assert.equal(await ownerRead('purchases'), null);
console.log(JSON.stringify({ MONTH_CARRY_FORWARD: 'PASS', MONTH_CARRY_REGRESSION: 'PASS', canonical_path: 'cash_carry_forwards/2026-09', opening_path: 'cash_month_openings/2026-09', production_target_used: 'NO' }, null, 2));
await signOut(auth);
process.exit(0);
